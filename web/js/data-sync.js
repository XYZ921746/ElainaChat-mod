// 端侧数据同步 —— **已由 web/js/store.js 取代（2026-09）**。
//
// ── 为什么这个文件被清空 ────────────────────────────────────────────────
//
// 用户实测："删除 data 分区后重新打开还是有数据。"
//
// 根因就在原实现里：它把 localStorage 当成**主存储**、把 data/ 当副本 ——
//   · 启动时把服务端 data/store.json 灌进 localStorage；
//   · 每次写 localStorage 再防抖推回服务端；
//   · **服务端缺、本机有的键还会反向补推上去**。
// 于是删掉 data/ 后重启，localStorage 里的数据又被推回去了 —— "删了还在"。
//
// 现在方向倒过来了：**data/ 是唯一权威存储**，内存缓存只是它的投影。
// 见 web/js/store.js 的完整说明。
//
// ── 这个文件为什么保留而不是删掉 ────────────────────────────────────────
//
// ① index.html 里的 <script src="/js/data-sync.js"> 若指向不存在的文件，
//    静态服务会回 404，浏览器控制台报错（虽不影响功能，但是噪音）。
// ② 老版本 APK 的 www/ 里还留着这个文件的旧内容，同步时要能覆盖掉它
//    —— 否则老 APK 升级后仍会跑旧的双向同步逻辑，问题照旧。
//
// 所以保留一个**空的、说明用途的**文件，而不是删除。
//
// ⚠️ 不要再往这里加同步逻辑，统一用 window.Store。
